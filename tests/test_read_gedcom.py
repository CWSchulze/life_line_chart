from life_line_chart import ReadGedcom
import os


def test_read_sample_file():
    data = ReadGedcom.read_data(os.path.join(
        os.path.dirname(__file__), 'gramps_sample.ged'))
    assert len(data[0]) == 42
    assert len(data[1]) == 15
    individual = data[0]['@I1@']
    assert individual['tag_data'] == 'INDI'
    assert individual['NAME']['tag_data'] == 'Keith Lloyd /Smith/'
    assert individual['SEX']['tag_data'] == 'M'
    assert individual['BIRT']['DATE']['tag_data'] == '11 AUG 1966'
    assert individual['BIRT']['PLAC']['tag_data'] == 'San Francisco, San Francisco Co., CA'
    assert individual['FAMC']['tag_data'] == '@F8@'
    assert individual['CHAN']['DATE']['TIME']['tag_data'] == '01:35:26'

    family = data[1]['@F1@']
    assert family['tag_data'] == 'FAM'
    assert family['HUSB']['tag_data'] == '@I27@'
    assert family['WIFE']['tag_data'] == '@I25@'
    assert family['MARR']['DATE']['tag_data'] == 'ABT 1790'
    assert family['MARR']['PLAC']['tag_data'] == 'Sweden'
    assert family['CHIL']['tag_data'] == '@I39@'
    assert family['CHAN']['DATE']['TIME']['tag_data'] == '01:35:26'


